import { redisKvFromUrl, STATE_KEY, LEASE_KEY, LEASE_META_KEY, CRON_KEY } from "./relay";
import { handleEngineRequest, loadDashboard } from "./vercel-live";
const kv = redisKvFromUrl(process.env.QA_REDIS!);
if (process.argv[2] === "reset") for (const k of [STATE_KEY, LEASE_KEY, LEASE_META_KEY, CRON_KEY]) await kv.del(k);
const now = Date.now();
const req = new Request("http://x/api/engine", { headers: { authorization: "Bearer qa" } });
const t = Date.now();
const res = await handleEngineRequest(req, { CRON_SECRET: "qa", P6_PRODUCTS: "BTC-USD,ETH-USD" }, { kv, nowMs: now, deadlineMs: now + 90_000, self: `qa-${now}` });
console.log("status", res.status, "secs", (Date.now() - t) / 1000, (await res.text()).slice(0, 300));
const raw = await kv.get(STATE_KEY);
const body = raw ? JSON.parse(raw) : null;
console.log("state bytes", raw?.length ?? 0, "fifteen", body?.fifteen?.length, "warmup", body?.warmup?.length, "hourWarm", body?.hourWarm?.map((x: any) => [x[0], x[1].length]), "gaps", JSON.stringify(body?.gaps), "historyFrom/cursors", JSON.stringify(body?.restCursor ?? body?.cursors ?? null)?.slice(0, 200));
console.log("incidents", JSON.stringify(body?.incidents ?? body?.book?.incidents ?? null)?.slice(0, 600));
const d: any = await loadDashboard(kv); console.log("dash g0", d.g0, JSON.stringify(d.gaps));
const keys = process.exit(0);
